"use client";

import { useJoin } from "agora-rtc-react";
import { MentorshipMeetingView } from "./mentorship-meeting-view";
import { useEffect } from "react";
import { toast } from "sonner";
import { LiveSessionProps } from "./live-room-client";

function getFriendlyJoinErrorMessage(error: {
  code?: string;
  message?: string;
}): string {
  switch (error.code) {
    case "CAN_NOT_GET_GATEWAY_SERVER":
    case "WS_ABORT":
    case "WS_DISCONNECT":
    case "WS_ERR":
      return "Couldn't reach the session server. Please check your internet connection and try again.";
    case "NETWORK_ERROR":
    case "NETWORK_TIMEOUT":
    case "TIMEOUT":
    case "API_INVOKE_TIMEOUT":
      return "The connection timed out. Please check your internet connection and try again.";
    case "UID_CONFLICT":
      return "You're already connected to this session from another tab or device.";
    case "INVALID_PARAMS":
    case "INVALID_TOKEN":
      return "Your session has expired. Please refresh the page to rejoin.";
    case "NOT_SUPPORTED":
      return "Your browser doesn't support video calls. Please use a recent version of Chrome, Firefox, Edge, or Safari.";
    case "PERMISSION_DENIED":
      return "Please allow camera and microphone access to join this session.";
    default:
      return "Something went wrong while joining the session. Please refresh the page and try again.";
  }
}

export function MentorshipLiveRoom(props: LiveSessionProps) {
  const appId = process.env.NEXT_PUBLIC_AGORA_APP_ID || "";

  // The token is now the real token generated by getAgoraLiveSessionAccess
  const { error: joinError } = useJoin({
    appid: appId,
    channel: props.meetingId,
    token: props.token,
    uid: props.numericUid,
  });

  useEffect(() => {
    if (joinError) {
      toast.error(getFriendlyJoinErrorMessage(joinError));
    }
  }, [joinError]);

  return (
    <MentorshipMeetingView
      {...props}
      leaveRedirectHref="/admin/mentorship_sessions"
    />
  );
}
